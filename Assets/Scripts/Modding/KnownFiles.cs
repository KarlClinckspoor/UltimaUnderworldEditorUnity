		public static Dictionary<string, string> For(GameKind g) { return g == GameKind.UW2 ? GogUw2 : GogUw1; }

		/// <summary>"gog-uw1" / "gog-uw2" when every hash is the GOG release's file, else "other".</summary>
		public static string SetOf(GameKind g, IDictionary<string, string> files)
		{
			var known = For(g);
			foreach (var kv in files)
			{
				string h;
				if (!known.TryGetValue(kv.Key, out h) || h != kv.Value) return "other";
			}
			return g == GameKind.UW2 ? "gog-uw2" : "gog-uw1";
		}

		/// <summary>The files of a folder that are not the GOG release's (changed, or not in it), and those missing.</summary>
		public static List<string> Differences(GameKind g, IFileSource folder, out List<string> missing)
		{
			var known = For(g);
			var r = new List<string>();
			missing = new List<string>();
			var seen = new HashSet<string>(StringComparer.Ordinal);
			foreach (var rel in folder.List())
			{
				seen.Add(rel);
				string h;
				if (!known.TryGetValue(rel, out h) || h != Hashing.Sha256(folder.Read(rel))) r.Add(rel);
			}
			foreach (var k in known.Keys) if (!seen.Contains(k)) missing.Add(k);
			return r;
		}
